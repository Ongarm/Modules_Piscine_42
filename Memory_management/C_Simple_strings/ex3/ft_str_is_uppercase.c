#include <stdio.h>

int	ft_str_is_uppercase(char *str)
{
	int	i;

	i = 0;
	while (str[i] != 0)
	{
		if (str[i] >= 'A' && str[i] <= 'Z')
			i++;
		else
			return (0);
	}
	return (1);
}

int    main(int argc, char **argv)
{
    if (argc == 2)
        printf("%d\n", ft_str_is_uppercase(argv[1]));
    return (0);
}
